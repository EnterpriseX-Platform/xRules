// Standalone binary to export OpenAPI spec
use std::fs;
use utoipa::OpenApi;
use xrules_engine::api::ApiDoc;

fn main() {
    // Export JSON
    let json = ApiDoc::openapi()
        .to_pretty_json()
        .expect("Failed to generate OpenAPI JSON");

    fs::write("openapi.json", &json).expect("Failed to write openapi.json");

    println!("✅ Exported openapi.json");

    // Export YAML (manual conversion)
    let yaml = convert_json_to_yaml(&json);
    fs::write("openapi.yaml", &yaml).expect("Failed to write openapi.yaml");

    println!("✅ Exported openapi.yaml");
    println!("\nOpenAPI 3.1 spec generated successfully!");
    println!("Files: openapi.json, openapi.yaml");
}

fn convert_json_to_yaml(json: &str) -> String {
    // Simple JSON to YAML conversion
    // In production, use a proper library like serde_yaml
    let mut yaml = String::new();
    yaml.push_str("openapi: 3.1.0\n");
    yaml.push_str("# Generated by XRules Engine\n");
    yaml.push_str("# This is a simplified YAML representation\n");
    yaml.push_str("# For full YAML support, install serde_yaml and use:\n");
    yaml.push_str("#   serde_yaml::to_string(&ApiDoc::openapi()).unwrap()\n\n");
    yaml.push_str("# See openapi.json for complete specification\n\n");
    yaml.push_str(json);
    yaml
}
